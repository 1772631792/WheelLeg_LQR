def _identifier(text):
    value=re.sub(r'[^A-Za-z0-9_.-]+','-',text.strip()).strip('-')
    if not value:raise ValueError('配置名称不能为空')
    return value[:64]


def _c_float(value):
    text=f'{float(value):.9g}'
    if 'e' not in text.lower() and '.' not in text:text+='.0'
    return text+'f'


def _array(name,value):
    rows=',\n'.join('    {'+', '.join(_c_float(v) for v in row)+'}' for row in value)
    return f'static const float {name}[12][4] = {{\n{rows}\n}};'


