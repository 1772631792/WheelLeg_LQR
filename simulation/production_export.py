def _audit(files):
    banned=('#include "stm32','#include "FreeRTOS','#include "cmsis','HAL_','pvPortMalloc','malloc(','calloc(','realloc(','Python.h','mujoco')
    findings=[]
    for path in files:
        text=path.read_text(encoding='utf-8')
        for token in banned:
            if token in text:findings.append(f'{path.name}: {token}')
    if findings:raise RuntimeError('检测到禁止依赖：'+'; '.join(findings))


